import { useEffect, useState } from 'react';
import Card from '../components/common/Card';
import LoadingSpinner from '../components/common/LoadingSpinner';
import EmptyState from '../components/common/EmptyState';
import { useAuth } from '../hooks/useAuth';
import { getPayrollByUser } from '../api/payrollApi';

export default function Payroll() {
  const { user } = useAuth();
  const [records, setRecords] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    getPayrollByUser(user.userId)
      .then(setRecords)
      .catch(() => setError('Could not load payroll records.'))
      .finally(() => setLoading(false));
  }, [user.userId]);

  if (loading) return <LoadingSpinner label="Loading payroll…" />;
  if (error) return <EmptyState title={error} />;

  const latest = records[records.length - 1];

  return (
    <section>
      <div className="eyebrow">{latest ? `${latest.payPeriod} cycle` : 'No cycle yet'}</div>
      <h1 className="headline">Money, <em>explained beautifully</em>.</h1>
      <p className="subhead">Every payslip generated by the backend, laid out clearly.</p>

      <div className="bento">
        <Card span={4} dark>
          <div className="titanium" style={{ fontSize: 11, textTransform: 'uppercase', letterSpacing: '.05em' }}>
            Latest Net Pay
          </div>
          <div style={{ fontFamily: 'var(--font-display)', fontSize: 30, margin: '10px 0' }}>
            {latest ? `₹${Number(latest.netPay).toLocaleString()}` : '—'}
          </div>
          {latest && (
            <div style={{ fontSize: 13 }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', padding: '8px 0', borderTop: '1px solid rgba(255,255,255,.08)' }}>
                <span>Base</span><span className="mono">₹{Number(latest.baseSalary).toLocaleString()}</span>
              </div>
              <div style={{ display: 'flex', justifyContent: 'space-between', padding: '8px 0', borderTop: '1px solid rgba(255,255,255,.08)' }}>
                <span>Bonus</span><span className="mono">₹{Number(latest.bonus || 0).toLocaleString()}</span>
              </div>
              <div style={{ display: 'flex', justifyContent: 'space-between', padding: '8px 0', borderTop: '1px solid rgba(255,255,255,.08)' }}>
                <span>Tax + PF</span><span className="mono">− ₹{(Number(latest.taxDeduction || 0) + Number(latest.pfDeduction || 0)).toLocaleString()}</span>
              </div>
            </div>
          )}
        </Card>

        <Card span={8}>
          <div className="section-title">Payroll History</div>
          {records.length === 0 ? (
            <EmptyState title="No payroll records" hint="Your HR team hasn't generated a payslip yet." />
          ) : (
            <div className="row-list">
              {records.slice().reverse().map((p) => (
                <div key={p.payrollId} className="row-item">
                  <div style={{ flex: 1, fontSize: 13, fontWeight: 600 }}>{p.payPeriod}</div>
                  <div className="titanium mono" style={{ fontSize: 12 }}>Base ₹{Number(p.baseSalary).toLocaleString()}</div>
                  <div className="mono" style={{ fontSize: 13 }}>₹{Number(p.netPay).toLocaleString()}</div>
                  <span className={`pill-tag ${p.status === 'Paid' ? 'tag-emerald' : 'tag-orange'}`}>{p.status}</span>
                </div>
              ))}
            </div>
          )}
        </Card>
      </div>
    </section>
  );
}
